  let result=dictionary[trimmed];
  if(result===undefined){
    for(const [key,value] of Object.entries(dictionary)) {
      if(!key.includes('{'))continue;
      const names:string[]=[];let pattern='^',cursor=0;
      for(const match of key.matchAll(/\{(\w+)\}/g)){pattern+=escape(key.slice(cursor,match.index))+'(.+?)';names.push(match[1]);cursor=match.index!+match[0].length;}
      pattern+=escape(key.slice(cursor))+'$';const match=new RegExp(pattern).exec(trimmed);
      if(match){result=value.replace(/\{(\w+)\}/g,(_,name)=>match[names.indexOf(name)+1]||'');break;}
    }
  }
